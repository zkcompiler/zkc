def source_modules(path):
    if path.suffix == ".toml":
        manifests = []
        modules, assets = project_inputs(path, manifests=manifests)
        if not (not assets):
            raise AssertionError('lean/bridges/structured/repeats.py: not assets')
        return dict(sorted(modules.items())), manifests
    return {"sample": path}, []


class RepeatSuite(OpenSuite):
    """Use OpenSuite comparisons with immutable tools and Git-free receipts."""

    source_scope = (
        "Git-free source owners: main Lake package namespaces; structured bridge, Lean checks/support, "
        "scripts and common test support; native compiler include/lib/tools/test/cmake and shared Unicode inputs; selected "
        "authored project module closures and retained subjects. External packages, optional Lean "
        "integrations, hidden/private/experiment directories and build caches excluded; "
        "native executables are retained separately, not rebuilt from this archive.")

    def source_inventory(self):
        lean = ROOT / "lean"
        paths = {lean / name for name in ("lean-toolchain", "lake-manifest.json", "lakefile.toml")}
        config = tomllib.loads((lean / "lakefile.toml").read_text(encoding="utf-8"))
        # Lake declarations own the namespaces, including executable roots
        # outside a library's globs. Capture each whole namespace so new local
        # imports are covered without a second per-module dependency list.
        for target in [*config.get("lean_lib", []), *config.get("lean_exe", [])]:
            directory = lean / target.get("srcDir", config.get("srcDir", "."))
            roots = target.get("roots", [target.get("root", target["name"])])
            if "root" in target:
                paths.add(directory / (target["root"].replace(".", "/") + ".lean"))
            for module in [*roots, *target.get("globs", [])]:
                owner = directory / module.split(".")[0]
                if not owner.with_suffix(".lean").exists() and not owner.is_dir():
                    raise FileNotFoundError(f"missing Lake source namespace: {owner}")
                if owner.with_suffix(".lean").exists():
                    paths.add(owner.with_suffix(".lean"))
                if owner.is_dir():
                    paths.update(owned_sources(owner, {".lean"}))
        for tree in ("scripts", "common/tests/support", "lean/checks", "lean/support"):
            paths.update(owned_sources(ROOT / tree, {".py"}))
        bridge = ROOT / "lean/bridges/structured"
        paths.update(owned_sources(bridge, {".py", ".md", ".json", ".mlir", ".zkc", ".toml"}))
        # Shared renderers and native Entry adapters are source dependencies.
        paths.update(owned_sources(ROOT / "lean/bridges/common", {".py"}))
        for tree in ("include", "lib", "tools", "test", "cmake"):
            paths.update(owned_sources(ROOT / "compiler" / tree,
                {".cpp", ".h", ".td", ".def", ".inc", ".cmake", ".in", ".txt",
                 ".py", ".json", ".mlir", ".zkc", ".toml"}))
        # compiler/cmake/Unicode.cmake consumes this shared source owner.
        paths.update(owned_sources(ROOT / "common/unicode", {".py", ".json", ".txt", ".md"}))
        paths.update(ROOT / name for name in (
            "compiler/CMakeLists.txt", "compiler/CMakePresets.json", "common/tests/run.py",
            "pyproject.toml", "uv.lock"))
        for stem, namespace, _, source in SUBJECTS:
            modules, manifests = source_modules(ROOT / source)
            paths.update(modules.values()); paths.update(manifests)
            paths.update(bridge / f"fixtures/{stem}.{suffix}" for suffix in ("json", "mlir"))
            paths.add(ROOT / f"lean/ZkcExamples/Structured/{namespace}Data.lean")
        return sorted(paths)

    def tool_names(self):
        return ("compiler", "reference") if self.args.native_only else ("compiler", "reference", "lean")

    def success_status(self):
        return "native-only" if self.args.native_only else "pass"

    def export(self, label, source, symbol="main"):
        if not self.args.native_only:
            return super().export(label, source, symbol)
        folder = self.directory / label
        folder.mkdir(exist_ok=True)
        original, path = folder / "source.mlir", folder / "source.json"
        original.write_text(source, encoding="utf-8")
        output = self.command(label + ":export", [self.tools["compiler"], "protocol-structured",
                                                original, "--symbol=" + symbol])
        data = json.loads(output)
        if not (data[:4] == ["zkc.structured-source/0", "original", "sha256:" + digest(original), symbol]):
            raise AssertionError('lean/bridges/structured/repeats.py: data[:4] == ["zkc.structured-source/0", "original", "sha256:" + digest(original), symbol]')
        path.write_text(output, encoding="utf-8")
        self.sources.append({"name": label, "source": str(original), "sha256": digest(original),
                             "snapshot": str(path), "snapshotSha256": digest(path),
                             "formalAdmission": "pending"})
        return original, path, data

    def compare_open(self, subject, label, role, inputs, replies, expected):
        if not self.args.native_only:
            return super().compare_open(subject, label, role, inputs, replies, expected)
        original, exported, data = subject
        request = exported.parent / (label + ".request.json")
        write_json(request, ["zkc.structured-open-request/0", role, inputs, replies, 1000000])
        native = json.loads(self.command(label + ":ssa", [self.tools["reference"], "open",
                                                         original, data[3], request]))
        if not (native == expected):
            raise AssertionError({"reference": native, "expected": expected})


def observe(suite, subject, label, role, inputs, replies, expected):
    suite.case(label, lambda: suite.compare_open(subject, label, role, inputs, replies, expected))


def instructions(block):
    for row in block[1]:
        yield row
        for region in row[3]:
            yield from instructions(region[2])


def body(subject):
    return definition(subject[2], subject[2][3])[9]


def roles(subject):
    return definition(subject[2], subject[2][3])[6][1]


def select(block, tag):
    return [row for row in block[1] if row[0][0] == tag]


def qualified(prefix, site):
    return f"apply_{len(prefix.encode('utf-8'))}_{prefix}_{site}" if prefix else site


def complete_sources(suite):
    result = {}
    for stem, namespace, entry, source in SUBJECTS:
        modules, _ = source_modules(ROOT / source)
        subject = suite.authored(stem, entry, modules, (stem, namespace))
        interface = json.loads((subject[1].parent / "interface.json").read_text(encoding="utf-8"))
        if not (interface["original"] == subject[2][2].removeprefix("sha256:")):
            raise AssertionError('lean/bridges/structured/repeats.py: interface["original"] == subject[2][2].removeprefix("sha256:")')
        if not (interface["protocol"] == subject[2][3]):
            raise AssertionError('lean/bridges/structured/repeats.py: interface["protocol"] == subject[2][3]')
        suite.case(stem + "-complete-fixture-bytes", lambda: None)
        result[stem] = subject
    return result


def repeat_cases(suite, subject):
    p, v = roles(subject)
    [loop] = select(body(subject), "protocol_repeat")
    [call] = select(loop[3][0][2], "protocol_apply")
    child = definition(subject[2], call[0][1])[9]
    [draw] = select(child, "draw"); [send] = select(child, "exchange")
    ds, ss = (qualified(call[4], row[4]) for row in (draw, send))
    receives = [reply(["receive", ss, v, p, FIELD_TYPE], value) for value in ("5", "7")]
    sends = []
    for value in ("2", "3"):
        sends += [reply(["draw", ds, v, SERVICE, "9", FIELD], value),
                  reply(["send", ss, v, p, FIELD_TYPE, value])]
    observe(suite, subject, "repeat-independent-P", p, ["2", "10", None, None, None], receives,
            returned(["22", None], receives))
    observe(suite, subject, "repeat-independent-V", v, ["2", None, "100", True, "9"], sends,
            returned([None, "105"], sends))
    observe(suite, subject, "repeat-independent-count-one", v, ["1", None, "100", True, "9"], sends,
            returned([None, "102"], sends[:2]))
    for label, count, expected in [("zero", "0", returned([None, "100"])),
                                   ("missing", None, stopped("incomplete", loop[4])),
                                   ("bound", "5", stopped("refused", loop[4]))]:
        observe(suite, subject, "repeat-" + label, v, [count, None, "100", None, None], sends, expected)
    [guard] = select(loop[3][0][2], "guard")
    for go, reason in [(False, "reject"), (None, "incomplete")]:
        observe(suite, subject, "repeat-guard-" + reason, v, ["1", None, "100", go, None], [],
                stopped(reason, guard[4]))
    failure_prefixes(suite, subject, "repeat-V", v, ["2", None, "100", True, "9"], sends, (2, 3))
    failure_prefixes(suite, subject, "repeat-P", p, ["2", "10", None, None, None], receives, (1,))
    # Preserve all declarations and names. Reachable arithmetic must be read.
    source = subject[0].read_text(encoding="utf-8")
    if not (source.count('"algebra.field_add"') == 2):
        raise AssertionError('lean/bridges/structured/repeats.py: source.count(\'"algebra.field_add"\') == 2')
    changed = suite.export("repeat-same-name-arithmetic", source.replace('"algebra.field_add"',
                           '"algebra.field_multiply"'), subject[2][3])
    if not (changed[2][2] != subject[2][2]):
        raise AssertionError('lean/bridges/structured/repeats.py: changed[2][2] != subject[2][2]')
    observe(suite, changed, "repeat-same-name-arithmetic-P", p, ["2", "10", None, None, None], receives,
            returned(["350", None], receives))
    observe(suite, changed, "repeat-same-name-arithmetic-V", v, ["2", None, "100", True, "9"], sends,
            returned([None, "600"], sends))


def nested_cases(suite, subject):
    [p] = roles(subject)
    [outer] = select(body(subject), "protocol_repeat")
    [inner] = select(outer[3][0][2], "protocol_repeat")
    for index, (n, m, x) in enumerate([(2, 2, 3), (3, 1, 7), (0, None, 11), (1, 0, 5)]):
        observe(suite, subject, f"nested-{index}", p,
                [str(n), None if m is None else str(m), str(x)], [],
                returned([str(x * (1 + n * (m or 0)))]))
    for label, inputs, site, reason in [
        ("missing-outer", [None, None, "3"], outer[4], "incomplete"),
        ("missing-inner", ["1", None, "3"], inner[4], "incomplete"),
        ("inner-bound", ["1", "3", "3"], inner[4], "refused"),
    ]:
        observe(suite, subject, "nested-" + label, p, inputs, [], stopped(reason, site))
    # A complete authored same-name change, before frontend emission.
    _, _, selected_subject, source = SUBJECTS[1]
    original = ROOT / source
    changed = suite.directory / "changed-repeat-nested.zkc"
    text = original.read_text(encoding="utf-8")
    if "result = result + x" not in text:
        raise AssertionError('lean/bridges/structured/repeats.py: "result = result + x" in text')
    changed.write_text(text.replace("result = result + x", "result = result * x"), encoding="utf-8")
    variant = suite.authored("nested-same-name-source", selected_subject, {"sample": changed})
    if not (variant[2][3] == subject[2][3] and variant[2][2] != subject[2][2]):
        raise AssertionError('lean/bridges/structured/repeats.py: variant[2][3] == subject[2][3] and variant[2][2] != subject[2][2]')
    observe(suite, variant, "nested-same-name-source-result", p, ["2", "2", "3"], [], returned(["243"]))


def failure_prefixes(suite, subject, label, role, inputs, responses, indices):
    for index in indices:
        action = responses[index][1]; prefix = responses[:index]
        aborted = prefix + [reply(action, stop="abort")]
        observe(suite, subject, f"{label}-abort-{index}", role, inputs, aborted + responses[index+1:],
                stopped("abort", action[1], aborted))
        observe(suite, subject, f"{label}-missing-{index}", role, inputs, prefix,
                stopped("incomplete", action[1], prefix, action))
        wrong = copy.deepcopy(responses[index]); wrong[1][1] = "wrong_site"
        observe(suite, subject, f"{label}-wrong-{index}", role, inputs, prefix + [wrong] + responses[index+1:],
                stopped("refused", action[1], prefix, action))


def service_cases(suite, subject, nested):
    prefix = ""
    current = body(subject)
    if nested:
        owner, outside, receiver = roles(subject)
        [outer] = select(current, "protocol_apply")
        if not (outer[0][2] == [receiver, owner]):
            raise AssertionError('lean/bridges/structured/repeats.py: outer[0][2] == [receiver, owner]')
        prefix = outer[4]
        current = definition(subject[2], outer[0][1])[9]
    else:
        receiver, owner = roles(subject)
    pre, post = [qualified(prefix, row[4]) for row in select(current, "draw")]
    [loop] = select(current, "protocol_repeat")
    [call] = select(loop[3][0][2], "protocol_apply")
    child = definition(subject[2], call[0][1])[9]
    nested_prefix = qualified(prefix, call[4])
    left, right = [qualified(nested_prefix, row[4]) for row in select(child, "draw")]
    [send] = select(child, "exchange"); delivery = qualified(nested_prefix, send[4])
    label = "service-wrapper" if nested else "service"

    def inputs(count, first=None, second=None):
        return [count, None, first, second] if nested else [count, first, second]

    def outputs(value, received=False):
        if nested:
            return [None, None, value] if received else [value, None, None]
        return [value, None] if received else [None, value]

    for alias in (False, True):
        handles = [11, 11 if alias else 17]; counters = {11: 0, 17: 0}; responses = []

        def draw(site, handle):
            counters[handle] += 1
            value = counters[handle]
            responses.append(reply(["draw", site, owner, SERVICE, str(handle), FIELD], str(value)))
            return value

        total = draw(pre, handles[0])
        for _ in range(2):
            value = draw(left, handles[0]) + draw(right, handles[1])
            responses.append(reply(["send", delivery, owner, receiver, FIELD_TYPE, str(value)]))
            total += value
        total += draw(post, handles[0])
        if not (counters == ({11: 6, 17: 0} if alias else {11: 4, 17: 2})):
            raise AssertionError('lean/bridges/structured/repeats.py: counters == ({11: 6, 17: 0} if alias else {11: 4, 17: 2})')
        observe(suite, subject, label + ("-alias" if alias else "-distinct"), owner,
                inputs("2", *map(str, handles)), responses, returned(outputs(str(total)), responses))
        if alias:
            # Prelude, both iterations, messages, and suffix are independent cut points.
            failure_prefixes(suite, subject, label, owner, inputs("2", *map(str, handles)), responses,
                             range(len(responses)))
    received = [reply(["receive", delivery, owner, receiver, FIELD_TYPE], v) for v in ("17", "23")]
    observe(suite, subject, label + "-independent-received", receiver, inputs("2"), received,
            returned(outputs("40", True), received))
    failure_prefixes(suite, subject, label + "-receive", receiver, inputs("2"), received, (0, 1))
    zero = [reply(["draw", site, owner, SERVICE, "11", FIELD], value)
            for site, value in [(pre, "2"), (post, "7")]]
    observe(suite, subject, label + "-zero-queries", owner, inputs("0", "11"), zero,
            returned(outputs("9"), zero))
    observe(suite, subject, label + "-zero-receiver", receiver, inputs("0"), received,
            returned(outputs("0", True)))
    if nested:
        observe(suite, subject, label + "-outsider", outside, [None, "41", None, None], received,
                returned([None, "41", None]))


def encoded(values):
    return [str(x % MODULUS) for x in values]


def msb_rounds(values, challenges):
    """Ordered contiguous halves; values/challenges are independent test inputs."""
    current = list(values); pairs = []
    for challenge in challenges:
        if not (len(current) >= 2 and len(current) % 2 == 0):
            raise AssertionError('lean/bridges/structured/repeats.py: len(current) >= 2 and len(current) % 2 == 0')
        half = len(current) // 2
        low, high = current[:half], current[half:]
        pairs.append((sum(low) % MODULUS, sum(high) % MODULUS))
        current = [(a + (b-a)*challenge) % MODULUS for a, b in zip(low, high, strict=True)]
    return pairs, current


def sumcheck_cases(suite, subject, complete):
    p, v = roles(subject)
    [application] = select(body(subject), "protocol_apply")
    reduction = definition(subject[2], application[0][1])[9]
    [loop] = select(reduction, "protocol_repeat"); callback = loop[3][0][2]
    exchanges = select(callback, "exchange")
    round0, round1, delivery = [qualified(application[4], row[4]) for row in exchanges]
    [draw] = select(callback, "draw"); draw_site = qualified(application[4], draw[4])
    [guard] = select(callback, "guard"); guard_site = qualified(application[4], guard[4])
    label = "sumcheck" if complete else "reduction"
    for rounds in (0, 1, 2):
        # P has its own table/count/received challenges; V has different values.
        values_p = [3, 11, 7, 19][:1 << rounds]
        challenges_p = [5, 7][:rounds]
        pairs_p, residual = msb_rounds(values_p, challenges_p)
        prover = []
        for pair, challenge in zip(pairs_p, challenges_p, strict=True):
            for site, value in zip((round0, round1), pair, strict=True):
                prover.append(reply(["send", site, p, v, FIELD_TYPE, str(value)]))
            prover.append(reply(["receive", delivery, v, p, FIELD_TYPE], str(challenge)))
        inputs_p = ([encoded(values_p), None, str(rounds), None] if complete else
                    [encoded(values_p), str(rounds), None, str(rounds), None])
        output_p = [None] if complete else [encoded(challenges_p), encoded(residual), None, None]
        observe(suite, subject, f"{label}-P-{rounds}", p, inputs_p, prover, returned(output_p, prover))

        values_v = [2, 13, 17, 29][:1 << rounds]
        challenges_v = [2, 3][:rounds]
        pairs_v, final_v = msb_rounds(values_v, challenges_v)
        verifier = []
        for pair, challenge in zip(pairs_v, challenges_v, strict=True):
            for site, value in zip((round0, round1), pair, strict=True):
                verifier.append(reply(["receive", site, p, v, FIELD_TYPE], str(value)))
            verifier += [reply(["draw", draw_site, v, SERVICE, "31", FIELD], str(challenge)),
                         reply(["send", delivery, v, p, FIELD_TYPE, str(challenge)])]
        claim = sum(values_v) % MODULUS
        inputs_v = ([encoded(values_v), str(claim), str(rounds), "31"] if complete else
                    [None, None, str(claim), str(rounds), "31"])
        output_v = [True] if complete else [None, None, encoded(challenges_v), str(final_v[0])]
        observe(suite, subject, f"{label}-V-{rounds}", v, inputs_v, verifier, returned(output_v, verifier))
        wrong = copy.deepcopy(inputs_v); wrong[1 if complete else 2] = str(claim + 1)
        expected = (returned([False]) if complete else returned([None, None, [], str(claim+1)])) if rounds == 0 else stopped("reject", guard_site, verifier[:2])
        observe(suite, subject, f"{label}-wrong-claim-{rounds}", v, wrong, verifier, expected)
        if complete and rounds:
            wrong_table = copy.deepcopy(inputs_v); wrong_table[0][0] = str(values_v[0]+1)
            observe(suite, subject, f"{label}-wrong-final-table-{rounds}", v, wrong_table, verifier,
                    returned([False], verifier))
        if rounds == 2:
            failure_prefixes(suite, subject, label + "-late-V", v, inputs_v, verifier, (4, 6, 7))
    # Count disagreement is permitted: these observations are never zipped into a run.
    observe(suite, subject, label + "-V-independent-zero-count", v,
            ([['7'], '7', '0', None] if complete else [None, None, '9', '0', None]), [],
            returned([True] if complete else [None, None, [], '9']))


def protocol(name, body_text="", roles=("P", "Q"),
             inputs=(("n", "ui64", ("P",)), ("x", "!F", ("P",)), ("c", "!F", ("P",))),
             outputs=(("!F", ("P",)),), returns=("%r",)):
    ins = ",".join(t for _, t, _ in inputs); outs = ",".join(t for t, _ in outputs)
    args = ",".join(f"%{n}:{t}" for n, t, _ in inputs)
    return f'''"protocol.func"() ({{ ^entry({args}):
      {body_text}
      "protocol.return"({','.join(returns)}) : ({outs})->()
    }}) {{sym_name="{name}",origin=["{name}",[]],function_type=({ins})->({outs}),roles={json.dumps(roles)},
      input_roles={json.dumps([s for _, _, s in inputs])},
      output_roles={json.dumps([s for _, s in outputs])}}} : ()->()'''


def module(*definitions):
    return '''!F = !algebra.field<"bls12-381.fr">
!S = !protocol.service_ref<"random.bls12-381.fr/0">
module { "protocol.module"() ({
''' + "\n".join(definitions) + '\n}) {profile=#protocol.profile<protocol>} : ()->() }'


def repeat(body_text="", yielded="%s", maximum=4):
    return f'''%r = "protocol.repeat"(%n,%x,%c) ({{
      ^body(%i:ui64,%s:!F,%capture:!F):
      {body_text}
      "protocol.yield"({yielded}) : (!F)->()
    }}) {{site="loop",carried=1:i64,maximum={maximum}:i64,roles=["P"],carried_roles=[["P"]]}} : (ui64,!F,!F)->!F'''


