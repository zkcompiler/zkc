        ("yield-arity", [3, 0, 2, 2], ["yield", []], "structured-formation"),
        ("callback-return", [3, 0, 2, 2], ["return", [1]], "structured-protocol-terminator"),
        ("callback-condition", [3, 0, 2, 2], ["condition", [1]], "structured-protocol-terminator"),
