        ("two-regions", [3], loop[3]*2, "structured-protocol-region"),
        ("region-input-type", [3, 0, 0, 0], ["bool"], "structured-protocol-signature"),
        ("region-extra-input", [3, 0, 0], loop[3][0][0]+[["field", FIELD]], "structured-protocol-signature"),
