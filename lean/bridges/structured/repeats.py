    subjects = complete_sources(suite)
    repeat_cases(suite, subjects["repeat"])
    nested_cases(suite, subjects["repeat-nested"])
    service_cases(suite, subjects["repeat-service"], False)
    service_cases(suite, subjects["repeat-service-wrapper"], True)
